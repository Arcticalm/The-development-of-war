"""Build lossless RGBA UI derivatives; never modify the accepted source portraits.

Usage: python scripts/build-unit-portraits.py
Requires Pillow. Only outer transparent pixels are cropped; no color quantization.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LONG_SIDE = 360
PADDING = 12


def build():
    plan = json.loads((ROOT / 'assets/units/generation-plan.json').read_text(encoding='utf-8'))
    index = {}
    output = ROOT / 'assets/unit-portraits'
    output.mkdir(exist_ok=True)
    for unit in plan:
        uid = unit['unit_id']
        age = uid.split('_', 1)[0]
        if uid in index or age not in ('age1', 'age2', 'age3', 'age4', 'age5'):
            raise ValueError('Invalid or duplicate unit ID: ' + uid)
        source = ROOT / 'assets/units' / age / (uid + '.png')
        source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
        with Image.open(source) as original:
            if original.mode != 'RGBA' or original.getchannel('A').getextrema() != (0, 255):
                raise ValueError('Expected transparent RGBA portrait: ' + str(source))
            content = original.crop(original.getchannel('A').getbbox())
            content.thumbnail((LONG_SIDE, LONG_SIDE), Image.Resampling.LANCZOS)
            portrait = Image.new('RGBA', (content.width + PADDING * 2, content.height + PADDING * 2))
            portrait.paste(content, (PADDING, PADDING))
            target = output / (uid + '.png')
            portrait.save(target, optimize=True)
        if hashlib.sha256(source.read_bytes()).hexdigest() != source_hash:
            raise RuntimeError('Source was modified: ' + str(source))
        index[uid] = {'path': target.relative_to(ROOT).as_posix(), 'width': portrait.width, 'height': portrait.height}
    if len(index) != 30 or any(sum(uid.startswith(age + '_') for uid in index) != 6 for age in ('age1', 'age2', 'age3', 'age4', 'age5')):
        raise ValueError('Expected 30 portraits, six per era')
    code = "'use strict';\n// Generated by scripts/build-unit-portraits.py. Do not edit by hand.\nmodule.exports=" + json.dumps(index, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'src/config/unit-portraits.js').write_text(code, encoding='utf-8')
    print(f'Built {len(index)} portraits: {sum((output / (uid + ".png")).stat().st_size for uid in index):,} bytes')


if __name__ == '__main__':
    build()
